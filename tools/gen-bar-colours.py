#!/usr/bin/env python3
"""
Writes the per-percent usage bar colours into source/aether-glass.css.

Every capacity bar, and the % number next to it on the Dashboard, takes one colour from
the bar's value, in 1% steps.  CSS can't read a number out of Unraid's markup, but it can
match text inside an attribute, and Unraid writes each bar's fill width into its style
attribute ("width:97%" from the server, "width: 62.4%" from the page's script).  So this
script writes, between marker lines in the CSS:

  BAR-COLOURS   the colour table (--aether-bar-0 to --aether-bar-100 on the page root),
                then one rule per whole percent that matches the bar's width and sets
                --aether-bar-v (the value) and --aether-bar-c (its colour) on the fill
  TEXT-COLOURS  one rule per whole percent that colours the % number in front of a bar
                from the same table, so the number always matches its bar

Each table entry is a CSS color-mix() of the two --aether-meter-sNN stops either side of
it, mixed the way a CSS linear-gradient mixes by default (straight sRGB).  The stops are
worked out from the Good, Warning and Critical colours set on the Settings page, so the
whole table follows those colours with no change here.  In the Spectrum bar style, where
the fill reveals the whole --aether-meter gradient, the colour at a bar's tip is the
table's colour for its value, and the number matches there too.

Everything outside the markers is left alone.  Run it from the repo folder after moving a
stop (change STOPS below and the matching --aether-meter-sNN line in the CSS):

    python3 tools/gen-bar-colours.py
"""
from pathlib import Path

CSS = Path(__file__).resolve().parent.parent / "source" / "aether-glass.css"

# The percent of each --aether-meter-sNN stop in aether-glass.css (keep the two in step)
STOPS = [0, 25, 45, 60, 72, 84, 92, 100]


def colour_at(v):
    """The scale's colour at v percent: a straight blend of the two stops either side."""
    if v in STOPS:
        return f"var(--aether-meter-s{v})"
    for a, b in zip(STOPS, STOPS[1:]):
        if a < v < b:
            share = round((b - v) / (b - a) * 100, 2)   # how much of the lower stop
            return f"color-mix(in srgb, var(--aether-meter-s{a}) {share:g}%, var(--aether-meter-s{b}))"
    raise ValueError(v)


def width_match(v):
    """The attribute tests for a fill that is v% wide.  Decimals round down."""
    spellings = [f"width:{v}%", f"width: {v}%"]
    if v < 100:
        spellings += [f"width:{v}.", f"width: {v}."]
    return ", ".join(f'[style*="{s}"]' for s in spellings)


def bar_block():
    lines = ["html:root {"]
    lines += [f"    --aether-bar-{v}: {colour_at(v)};" for v in range(101)]
    lines.append("}")
    lines += [f"body :is(.usage-disk, .usage-bar) > span:first-child:is({width_match(v)}) "
              f"{{ --aether-bar-v: {v}; --aether-bar-c: var(--aether-bar-{v}); }}" for v in range(101)]
    return lines


def text_block():
    return [f'body span.load:not([style*="color"]):has(+ .usage-disk:not(.none) > span:first-child:is({width_match(v)})) '
            f"{{ color: var(--aether-bar-{v}) !important; }}" for v in range(101)]


def fill(css, name, lines):
    start = f"/* {name}:START"
    end = f"/* {name}:END */"
    head, sep, rest = css.partition(start)
    if not sep:
        raise SystemExit(f"marker not found in {CSS.name}: {start}")
    _, sep, tail = rest.partition(end)
    if not sep:
        raise SystemExit(f"marker not found in {CSS.name}: {end}")
    note = f"{start} (generated by tools/gen-bar-colours.py: edit the script, not this block) */"
    return head + "\n".join([note, *lines, end]) + tail


def main():
    css = CSS.read_text()
    css = fill(css, "BAR-COLOURS", bar_block())
    css = fill(css, "TEXT-COLOURS", text_block())
    CSS.write_text(css)
    print(f"wrote the 1% colour table, 101 bar rules and 101 text rules into {CSS.name}")


if __name__ == "__main__":
    main()
